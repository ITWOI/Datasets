static standardConfig * lookupConfig (const sds name){
    dictEntry *de = dictFind(configs, name);
    return de ? dictGetVal(de) : ((void *)0);
}


extern struct rewriteConfigState * rewriteConfigCreateState (){
    struct rewriteConfigState *state = zmalloc(sizeof (*state));
    state->option_to_line = dictCreate(&optionToLineDictType);
    state->rewritten = dictCreate(&optionSetDictType);
    state->numlines = 0;
    state->lines = ((void *)0);
    state->needs_signature = 1;
    state->force_write = 0;
    return state;
}


extern void rewriteConfigAppendLine (struct rewriteConfigState *state, sds line){
    state->lines = zrealloc(state->lines, sizeof(char *) * (state->numlines + 1));
    state->lines[state->numlines++] = line;
}


extern struct rewriteConfigState * rewriteConfigReadOldFile (char *path){
    FILE *fp = fopen(path, "r");
    if (fp == ((void *)0) && (*__errno_location()) != 2)
        return ((void *)0);
    struct stat sb;
    if (fp && fstat(fileno(fp), &sb) == -1) {
        ;
        return ((void *)0);
    }
    int linenum = -1;
    struct rewriteConfigState *state = rewriteConfigCreateState();
    if (fp == ((void *)0)) {
        return state;
    }
    if (sb.st_size == 0) {
        ;
        return state;
    }
    sds config = sdsnewlen(SDS_NOINIT, sb.st_size);
    if (fread(config, 1, sb.st_size, fp) == 0) {
        ;
        ;
        ;
        return ((void *)0);
    }
    int i, totlines;
    sds *lines = sdssplitlen(config, sdslen(config), "\n", 1, &totlines);
    for (i = 0; i < totlines; i++) {
        int argc;
        sds *argv;
        sds line = sdstrim(lines[i], "\r\n\t ");
        lines[i] = ((void *)0);
        linenum++;
        if (line[0] == '#' || line[0] == '\x00') {
            if (state->needs_signature && !strcmp(line, "# Generated by CONFIG REWRITE"))
                state->needs_signature = 0;
            rewriteConfigAppendLine(state, line);
            continue;
        }
        argv = sdssplitargs(line, &argc);
        if (argv == ((void *)0) || (!lookupConfig(argv[0]) && strcasecmp(argv[0], "include") && strcasecmp(argv[0], "rename-command") && strcasecmp(argv[0], "user") && strcasecmp(argv[0], "loadmodule") && strcasecmp(argv[0], "sentinel"))) {
            sds aux = sdsnew("# ??? ");
            aux = sdscatsds(aux, line);
            ;
            ;
            rewriteConfigAppendLine(state, aux);
            continue;
        }
        ;
        rewriteConfigAppendLine(state, line);
        standardConfig *s_conf = lookupConfig(argv[0]);
        if (s_conf && s_conf->flags & (1ULL << 7)) {
            ;
            argv[0] = sdsnew(s_conf->alias);
        }
        if (server.sentinel_mode && argc > 1 && !strcasecmp(argv[0], "sentinel")) {
            sds sentinelOption = sdsempty();
            sentinelOption = sdscatfmt(sentinelOption, "%S %S", argv[0], argv[1]);
            ;
            ;
        } else {
            ;
        }
        ;
    }
    ;
    ;
    ;
    return state;
}


extern int rewriteConfigRewriteLine (struct rewriteConfigState *state, const char *option, sds line, int force){
    sds o = sdsnew(option);
    list *l = dictFetchValue(state->option_to_line, o);
    ;
    if (!l && !force && !state->force_write) {
        ;
        ;
        return 0;
    }
    if (l) {
        listNode *ln = ((l)->head);
        int linenum = (long)ln->value;
        ;
        ;
        ;
        state->lines[linenum] = line;
    } else {
        if (state->needs_signature) {
            rewriteConfigAppendLine(state, sdsnew("# Generated by CONFIG REWRITE"));
            state->needs_signature = 0;
        }
        rewriteConfigAppendLine(state, line);
    }
    ;
    return 1;
}


extern void rewriteConfigUserOption (struct rewriteConfigState *state){
    if (server.acl_filename[0] != '\x00') {
        ;
        return;
    }
    raxIterator ri;
    ;
    ;
    while (raxNext(&ri))
        {
            user *u = ri.data;
            sds line = sdsnew("user ");
            line = sdscatsds(line, u->name);
            line = sdscatlen(line, " ", 1);
            robj *descr = ACLDescribeUser(u);
            line = sdscatsds(line, descr->ptr);
            ;
            rewriteConfigRewriteLine(state, "user", line, 1);
        }
    ;
    ;
}


extern void rewriteConfigLoadmoduleOption (struct rewriteConfigState *state){
    sds line;
    dictIterator di;
    dictEntry *de;
    ;
    while ((de = dictNext(&di)) != ((void *)0))
        {
            struct RedisModule *module = dictGetVal(de);
            if (sdslen(module->loadmod->path) == 0)
                continue;
            ;
            line = sdsnew("loadmodule ");
            line = sdscatsds(line, module->loadmod->path);
            for (int i = 0; i < module->loadmod->argc; i++) {
                line = sdscatlen(line, " ", 1);
                line = sdscatsds(line, module->loadmod->argv[i]->ptr);
            }
            rewriteConfigRewriteLine(state, "loadmodule", line, 1);
        }
    ;
    ;
}


extern sds rewriteConfigGetContentFromState (struct rewriteConfigState *state){
    sds content = sdsempty();
    int j, was_empty = 0;
    for (j = 0; j < state->numlines; j++) {
        if (sdslen(state->lines[j]) == 0) {
            if (was_empty)
                continue;
            ;
            was_empty = 1;
        } else {
            was_empty = 0;
        }
        content = sdscatsds(content, state->lines[j]);
        content = sdscatlen(content, "\n", 1);
    }
    return content;
}


extern void rewriteConfigRemoveOrphaned (struct rewriteConfigState *state){
    dictIterator di;
    dictEntry *de;
    ;
    while ((de = dictNext(&di)) != ((void *)0))
        {
            list *l = dictGetVal(de);
            sds option = dictGetKey(de);
            if (dictFind(state->rewritten, option) == ((void *)0)) {
                ;
                continue;
            }
            while (((l)->len))
                {
                    listNode *ln = ((l)->head);
                    int linenum = (long)ln->value;
                    sdsfree(state->lines[linenum]);
                    state->lines[linenum] = sdsempty();
                    ;
                }
        }
    ;
}


extern int rewriteConfigOverwriteFile (char *configfile, sds content){
    int fd = -1;
    int retval = -1;
    char tmp_conffile[4096];
    const char *tmp_suffix = ".XXXXXX";
    size_t offset = 0;
    ssize_t written_bytes = 0;
    int old_errno;
    int tmp_path_len = snprintf(tmp_conffile, sizeof (tmp_conffile), "%s%s", configfile, tmp_suffix);
    if (tmp_path_len <= 0 || (unsigned int)tmp_path_len >= sizeof (tmp_conffile)) {
        ;
        ;
        return retval;
    }
    fd = mkostemp(tmp_conffile, 524288);
    if (fd == -1) {
        ;
        return retval;
    }
    while (offset < sdslen(content))
        {
            written_bytes = write(fd, content + offset, sdslen(content) - offset);
            if (written_bytes <= 0) {
                if ((*__errno_location()) == 4)
                    continue;
                ;
                ;
                goto cleanup;
            }
            offset += written_bytes;
        }
  cleanup:
    ;
    ;
    ;
    ;
    return retval;
}


extern int rewriteConfig (char *path, int force_write){
    struct rewriteConfigState *state;
    sds newcontent;
    int retval;
    if ((state = rewriteConfigReadOldFile(path)) == ((void *)0))
        return -1;
    if (force_write)
        state->force_write = 1;
    dictIterator di;
    dictEntry *de;
    ;
    ;
    rewriteConfigUserOption(state);
    rewriteConfigLoadmoduleOption(state);
    ;
    rewriteConfigRemoveOrphaned(state);
    newcontent = rewriteConfigGetContentFromState(state);
    retval = rewriteConfigOverwriteFile(server.configfile, newcontent);
    ;
    ;
    return retval;
}


